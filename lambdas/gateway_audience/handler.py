"""CloudFormation custom resource: set the gateway's JWT allowed audience to the gateway's own ID.

Amazon Connect sends a JWT whose "aud" claim is the gateway ID. The ID is generated by the service
when the gateway is created, so CloudFormation cannot put it into the gateway's own definition.
This handler runs right after the gateway is created or updated (same deployment) and patches it.

It does a read-modify-write: every field returned by GetGateway that UpdateGateway accepts is sent
back unchanged, and only customJWTAuthorizer.allowedAudience is replaced.
"""
import logging
import time

import boto3

logger = logging.getLogger()
logger.setLevel(logging.INFO)

CLIENT = boto3.client("bedrock-agentcore-control")
UPDATE_FIELDS = set(CLIENT.meta.service_model.operation_model("UpdateGateway").input_shape.members)
WAIT_SECONDS = 600


def _wait_until_ready(gateway_id: str) -> dict:
    deadline = time.time() + WAIT_SECONDS
    while True:
        gateway = CLIENT.get_gateway(gatewayIdentifier=gateway_id)
        status = gateway["status"]
        if status == "READY":
            return gateway
        if status == "FAILED" or time.time() > deadline:
            raise RuntimeError(f"Gateway {gateway_id} status {status}: {gateway.get('statusReasons')}")
        time.sleep(5)


def _set_audience(gateway_id: str) -> None:
    gateway = _wait_until_ready(gateway_id)
    jwt = gateway.get("authorizerConfiguration", {}).get("customJWTAuthorizer")
    if gateway.get("authorizerType") != "CUSTOM_JWT" or jwt is None:
        raise RuntimeError(f"Gateway {gateway_id} must use CUSTOM_JWT, found {gateway.get('authorizerType')}")
    if jwt.get("allowedAudience") == [gateway_id]:
        logger.info("Allowed audience already set to %s", gateway_id)
        return

    request = {k: v for k, v in gateway.items() if k in UPDATE_FIELDS}
    request["gatewayIdentifier"] = gateway_id
    request["authorizerConfiguration"] = {"customJWTAuthorizer": {**jwt, "allowedAudience": [gateway_id]}}
    CLIENT.update_gateway(**request)
    _wait_until_ready(gateway_id)
    logger.info("Allowed audience set to %s", gateway_id)


def on_event(event, _context):
    logger.info("RequestType=%s", event["RequestType"])
    gateway_id = event["ResourceProperties"]["GatewayId"]
    if event["RequestType"] in ("Create", "Update"):
        _set_audience(gateway_id)
    # Delete: nothing to undo, CloudFormation deletes the gateway itself.
    return {"PhysicalResourceId": f"{gateway_id}-audience"}
